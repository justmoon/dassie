//! Writes the rate feed's golden vectors (spec/areas/rate-feed.md#test-vectors)
//! to standard output, from the fixed key of `tests/support` (the seed is
//! the bytes 0 to 31). Ed25519 signs deterministically, so the output is the
//! same every time. From the repository root:
//!
//! ```text
//! cargo run -p dassie-feed --example feed_vectors > testdata/feed/vectors.json
//! ```
//!
//! The feed's wire format is frozen within its version
//! (spec/overview.md#frozen-surfaces): running this again must not change
//! the committed file, and `tests/vectors.rs` fails if the code no longer
//! makes or reads those bytes.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::cast_possible_truncation
)]

#[path = "../tests/support/mod.rs"]
mod support;

use dassie_feed::{Cookie, Feed, assemble_feed, encode_challenge, encode_subscribe, sign_feed};
use dassie_identity::{NodeKey, Signature};
use serde_json::{Value, json};
use support::{empty_feed, hex, key, largest_feed, longest_ids, other_key, two_method_feed};

fn main() {
    let key = key();
    let ids = longest_ids();
    let feeds = [
        ("heartbeat", empty_feed()),
        ("two methods", two_method_feed()),
        ("largest", largest_feed(&ids)),
    ];
    let cookie = Cookie::from_bytes(core::array::from_fn(|index| 0xc0 + index as u8));
    let vectors = json!({
        "comment": "Generated by crates/dassie-feed/examples/feed_vectors.rs; see its header. Do not edit.",
        "seed": hex(&support::SEED),
        "publicKey": hex(key.public_key().as_bytes()),
        "slhDsaPublicKey": hex(key.slh_dsa_public_key().as_bytes()),
        "nodeId": key.identity().node_id().as_str(),
        "subscribe": [
            { "cookie": null, "datagram": hex(&encode_subscribe(None)) },
            { "cookie": hex(cookie.as_bytes()), "datagram": hex(&encode_subscribe(Some(&cookie))) },
        ],
        "challenge": [
            { "cookie": hex(cookie.as_bytes()), "datagram": hex(&encode_challenge(&cookie)) },
        ],
        "feeds": feeds.iter().map(|(name, feed)| feed_vector(name, &key, feed)).collect::<Vec<_>>(),
        "refused": refused(&key),
    });
    println!("{}", serde_json::to_string_pretty(&vectors).unwrap());
}

/// A feed, its fields and its datagram.
fn feed_vector(name: &str, key: &NodeKey, feed: &Feed<'_>) -> Value {
    let datagram = sign_feed(key, feed).unwrap();
    json!({
        "name": name,
        "sequenceMs": feed.sequence_ms,
        "validUntilMs": feed.valid_until_ms,
        "feePpm": feed.fee_ppm,
        "methods": feed.methods.iter().map(|method| json!([method.id, method.max_packet_amount])).collect::<Vec<_>>(),
        "rates": feed.rates.iter().map(|rate| json!([rate.from, rate.to, rate.rate_e15])).collect::<Vec<_>>(),
        "datagram": hex(&datagram),
    })
}

/// Feeds that decode but must not verify, and datagrams that must not
/// decode, each with the error.
fn refused(key: &NodeKey) -> Value {
    let feed = two_method_feed();
    let signed = feed.signed_bytes().unwrap();

    let mut tampered = key.sign(&signed).as_bytes().to_owned();
    tampered[0] ^= 1;
    let tampered = assemble_feed(&signed, &Signature::from_bytes(tampered));

    // Signed by another key than the one it names.
    let other = other_key();
    let foreign = assemble_feed(&signed, &other.sign(&signed));

    // The identity point, a key of small order, with a signature that
    // verifies under ZIP-215 for every message: R the identity, s zero.
    let mut weak = [0u8; 32];
    weak[0] = 1;
    let mut small = feed.clone();
    small.public_key = weak;
    let small_signed = small.signed_bytes().unwrap();
    let mut signature = [0u8; 64];
    signature[0] = 1;
    let small = assemble_feed(&small_signed, &Signature::from_bytes(signature));

    // Version 1, which named ledgers, is another version now.
    let mut version = sign_feed(key, &feed).unwrap();
    version[0] = 1;

    json!([
        { "name": "tampered signature", "datagram": hex(&tampered), "error": "Signature" },
        { "name": "signed by another key", "datagram": hex(&foreign), "error": "Signature" },
        { "name": "small-order key", "datagram": hex(&small), "error": "PublicKey" },
        { "name": "version 1", "datagram": hex(&version), "error": "Version" },
    ])
}
