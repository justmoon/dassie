//! Writes the snapshot's golden vectors (spec/areas/rate-feed.md#test-vectors)
//! to standard output, from the fixed key of `tests/support` (the seed is
//! the bytes 0 to 31). Ed25519 signs deterministically, so the output is the
//! same every time. From the repository root:
//!
//! ```text
//! cargo run -p dassie-feed --example snapshot_vectors > testdata/feed/snapshots.json
//! ```
//!
//! The snapshot's wire format is frozen within its version once a release
//! carries it (spec/overview.md#frozen-surfaces): running this again must
//! not change the committed file, and `tests/snapshot_vectors.rs` fails if
//! the code no longer makes or reads those bytes.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::cast_possible_truncation
)]

#[path = "../tests/support/mod.rs"]
mod support;

use dassie_feed::number::{STEP_FRACTIONS, amount16_floor};
use dassie_feed::snapshot::TAG_DOMAIN;
use dassie_feed::{
    Ladder, MethodQuotes, Quote, REQUEST_BYTES, Ratio, Snapshot, attach_signature, encode_request,
    method_tag, sign_snapshot, snapshot_signing_message,
};
use dassie_identity::{NodeKey, Signature};
use serde_json::{Value, json};
use support::{
    closed_side_snapshot, empty_snapshot, hex, key, largest_snapshot, other_key,
    two_method_snapshot,
};

/// Scheme IDs whose tags the vectors pin.
const SCHEME_IDS: [&str; 4] = [
    "hub-xrpl-testnet-dsusd",
    "hub-xrpl-testnet-xrp",
    "hub-xrpl-xrp",
    "xrpl-testnet-xrp",
];

/// Ratios whose quotes the vectors pin, as decimal strings.
const RATIOS: [(u128, u128); 8] = [
    (0, 1),
    (1, 1),
    (1, 3),
    (249, 100),
    (1_001, 1_000),
    (1, u128::MAX),
    (u128::MAX, 1),
    ((1 << 25) - 1, 1 << 24),
];

/// Amounts whose first-amount floats the vectors pin.
const AMOUNTS: [u64; 6] = [0, 1_023, 1_024, 1_025, 40_000_000, u64::MAX];

fn main() {
    let key = key();
    let snapshots = [
        ("heartbeat", empty_snapshot()),
        ("two methods", two_method_snapshot()),
        ("closed side", closed_side_snapshot()),
        ("largest", largest_snapshot()),
    ];
    let vectors = json!({
        "comment": "Generated by crates/dassie-feed/examples/snapshot_vectors.rs; see its header. Do not edit.",
        "seed": hex(&support::SEED),
        "publicKey": hex(key.public_key().as_bytes()),
        "tagDomain": String::from_utf8(TAG_DOMAIN.to_vec()).unwrap(),
        "tags": SCHEME_IDS.iter().map(|id| json!({ "schemeId": id, "tag": hex(&method_tag(id)) })).collect::<Vec<_>>(),
        "quotes": RATIOS.iter().map(|&(numerator, denominator)| json!({
            "numerator": numerator.to_string(),
            "denominator": denominator.to_string(),
            "floor": format!("{:08x}", Quote::floor(numerator, denominator).to_bits()),
            "ceil": format!("{:08x}", Quote::ceil(numerator, denominator).to_bits()),
        })).collect::<Vec<_>>(),
        "firstAmounts": AMOUNTS.iter().map(|&amount| json!({
            "amount": amount,
            "bits": format!("{:04x}", amount16_floor(amount)),
        })).collect::<Vec<_>>(),
        "stepFractions": STEP_FRACTIONS.iter().map(|fraction| format!("{fraction:016x}")).collect::<Vec<_>>(),
        "ladders": ladders(),
        "request": hex(&encode_request()),
        "snapshots": snapshots.iter().map(|(name, snapshot)| snapshot_vector(name, &key, snapshot)).collect::<Vec<_>>(),
        "swaps": swaps(),
        "refused": refused(&key),
    });
    println!("{}", serde_json::to_string_pretty(&vectors).unwrap());
}

/// Ladders made from amounts, with their bytes and what they decode to.
fn ladders() -> Value {
    let cases: [[u64; 8]; 5] = [
        [0; 8],
        [1_000, 2_000, 4_000, 8_000, 16_000, 32_000, 64_000, 128_000],
        [1, 2, 3, 5, 8, 13, 21, 34],
        [
            500,
            400,
            600,
            1_000_000,
            1_000_000,
            3_000_000,
            1 << 40,
            1 << 41,
        ],
        [u64::MAX; 8],
    ];
    cases
        .iter()
        .map(|&amounts| {
            let ladder = Ladder::floor(amounts);
            json!({
                "amounts": amounts,
                "bytes": hex(&ladder.to_bytes()),
                "decoded": ladder.amounts(),
            })
        })
        .collect::<Vec<_>>()
        .into()
}

fn method_vector(method: &MethodQuotes) -> Value {
    json!({
        "tag": hex(&method.tag),
        "bid": format!("{:08x}", method.bid.to_bits()),
        "ask": format!("{:08x}", method.ask.to_bits()),
        "bidLadder": hex(&method.bid_ladder.to_bytes()),
        "askLadder": hex(&method.ask_ladder.to_bytes()),
    })
}

/// A snapshot, its fields and its bytes.
fn snapshot_vector(name: &str, key: &NodeKey, snapshot: &Snapshot) -> Value {
    json!({
        "name": name,
        "sequenceMs": snapshot.sequence_ms,
        "validUntilMs": snapshot.valid_until_ms,
        "gridBp": snapshot.grid_bp,
        "methods": snapshot.methods.iter().map(method_vector).collect::<Vec<_>>(),
        "datagram": hex(&sign_snapshot(key, snapshot).unwrap()),
    })
}

/// Swaps priced from the two-method snapshot, both ways.
fn swaps() -> Value {
    let snapshot = two_method_snapshot();
    let (dsusd, xrp) = (SCHEME_IDS[0], SCHEME_IDS[1]);
    let mut swaps = Vec::new();
    for (from, to) in [(dsusd, xrp), (xrp, dsusd)] {
        for amount_in in [0u64, 1, 1_000_000, 50_000_000, 1 << 40] {
            let out = snapshot.swap_out(method_tag(from), method_tag(to), amount_in);
            swaps.push(json!({
                "from": from, "to": to, "amountIn": amount_in, "amountOut": out,
            }));
        }
        for (numerator, denominator) in [(0u64, 1u64), (39, 100), (2, 5), (247, 100), (5, 2)] {
            let threshold = Ratio::new(numerator, denominator).unwrap();
            let swap = snapshot
                .swap_at_least(method_tag(from), method_tag(to), threshold)
                .unwrap();
            swaps.push(json!({
                "from": from, "to": to, "threshold": [numerator, denominator],
                "amountIn": swap.amount_in, "amountOut": swap.amount_out,
            }));
        }
    }
    swaps.into()
}

/// Where the first method starts: the version, the tag, the sequence, the
/// validity, the grid and the count.
const FIRST_METHOD: usize = 1 + 1 + 8 + 8 + 16 + 2;

/// The two-method snapshot's bytes with `change` made before signing,
/// signed again, so that only the change is wrong.
fn changed(key: &NodeKey, change: impl FnOnce(&mut Vec<u8>)) -> String {
    let mut unsigned = two_method_snapshot().unsigned_bytes().unwrap();
    change(&mut unsigned);
    let signature = key.sign(&snapshot_signing_message(&unsigned));
    hex(&attach_signature(unsigned, &signature))
}

/// Datagrams that must not decode, and snapshots that decode but must not
/// verify, each with the error.
fn refused(key: &NodeKey) -> Value {
    let unsigned = two_method_snapshot().unsigned_bytes().unwrap();
    let message = snapshot_signing_message(&unsigned);

    let mut tampered = key.sign(&message).as_bytes().to_owned();
    tampered[0] ^= 1;
    let tampered = attach_signature(unsigned.clone(), &Signature::from_bytes(tampered));
    let foreign = attach_signature(unsigned.clone(), &other_key().sign(&message));
    let without_oid = attach_signature(unsigned.clone(), &key.sign(&unsigned));
    // The identity point: of small order, so weak.
    let mut weak = [0u8; 32];
    weak[0] = 1;

    let mut padded = encode_request();
    padded[100] = 1;

    json!([
        { "name": "tampered signature", "datagram": hex(&tampered), "error": "Signature" },
        { "name": "signed by another key", "datagram": hex(&foreign), "error": "Signature" },
        { "name": "signed without the OID", "datagram": hex(&without_oid), "error": "Signature" },
        { "name": "checked against a weak key", "datagram": changed(key, |_| {}), "key": hex(&weak), "error": "PublicKey" },
        { "name": "version 1", "datagram": changed(key, |bytes| bytes[0] = 1), "error": "Version" },
        { "name": "valid until its sequence", "datagram": changed(key, |bytes| {
            let sequence: Vec<u8> = bytes[2..10].to_vec();
            bytes[10..18].copy_from_slice(&sequence);
        }), "error": "ValidUntil" },
        { "name": "drops not ascending", "datagram": changed(key, |bytes| bytes.swap(19, 21)), "error": "Grid" },
        { "name": "drop of 100%", "datagram": changed(key, |bytes| {
            bytes[32..34].copy_from_slice(&10_000u16.to_be_bytes());
        }), "error": "Grid" },
        { "name": "methods out of order", "datagram": changed(key, |bytes| {
            let (first, second) = bytes[FIRST_METHOD..].split_at_mut(30);
            first.swap_with_slice(&mut second[..30]);
        }), "error": "TagOrder" },
        { "name": "quote not normalized", "datagram": changed(key, |bytes| bytes[FIRST_METHOD + 5] &= 0x7f), "error": "Quote" },
        { "name": "closed bid with a ladder", "datagram": changed(key, |bytes| {
            bytes[FIRST_METHOD + 4..FIRST_METHOD + 8].fill(0);
        }), "error": "ClosedLadder" },
        { "name": "step not the smallest", "datagram": changed(key, |bytes| {
            // The first amount 1 never grows: only step 0 is canonical.
            bytes[FIRST_METHOD + 12..FIRST_METHOD + 21].copy_from_slice(&[0, 1, 1, 0, 0, 0, 0, 0, 0]);
        }), "error": "Ladder" },
        { "name": "request with padding not zero", "datagram": hex(&padded), "error": "Decode" },
        { "name": "request one byte short", "datagram": hex(&encode_request()[..REQUEST_BYTES - 1]), "error": "Decode" },
    ])
}
