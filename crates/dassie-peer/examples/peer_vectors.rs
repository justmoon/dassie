//! Writes the peer protocol's golden vectors
//! (spec/areas/peer-protocol.md#test-vectors) to standard output, from the
//! fixed keys of `tests/support/vectors.rs`. Ed25519 signs
//! deterministically, so the output is the same every time. From the
//! repository root:
//!
//! ```text
//! cargo run -p dassie-peer --example peer_vectors > crates/dassie-peer/tests/data/vectors.json
//! ```
//!
//! The layouts are frozen within a protocol version
//! (spec/overview.md#frozen-surfaces): running this again must not change
//! the committed file, and `tests/vectors.rs` fails if the code no longer
//! makes or reads those bytes. A change to them is a new version.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::panic,
    clippy::print_stdout
)]

#[allow(dead_code)]
#[path = "../tests/support/inputs.rs"]
mod inputs;
#[path = "../tests/support/vectors.rs"]
mod vectors;

use serde_json::{Map, Value, json};

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn table(entries: std::collections::BTreeMap<String, Vec<u8>>) -> Value {
    Value::Object(
        entries
            .into_iter()
            .map(|(name, bytes)| (name, Value::String(hex(&bytes))))
            .collect::<Map<_, _>>(),
    )
}

fn main() {
    let vectors = json!({
        "comment": "Generated by crates/dassie-peer/examples/peer_vectors.rs; see its header. Do not edit.",
        "version": vectors::VERSION,
        "nodeA": {
            "seed": hex(&[1; 32]),
            "publicKey": hex(vectors::node_a().public_key().as_bytes()),
            "nodeId": vectors::node_a().node_id().as_str(),
        },
        "nodeB": {
            "seed": hex(&[3; 32]),
            "publicKey": hex(vectors::node_b().public_key().as_bytes()),
            "nodeId": vectors::node_b().node_id().as_str(),
        },
        "linkState": hex(&vectors::link_state()),
        "messages": table(vectors::messages()),
        "answers": table(vectors::answers()),
    });
    println!("{}", serde_json::to_string_pretty(&vectors).unwrap());
}
